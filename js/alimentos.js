/** Formas de preparar de un alimento (solo los de la base; los propios no llevan). */
function prepOf(food) {
  if (!food || food.mine) return null;
  const s = normTxt(food.n), g = PREP_GROUPS.find(([, re]) => re.test(s));
  return g ? PREP[g[0]] : null;
}
/** Calorías y macros de `grams` g del alimento con una forma de preparar (aceite real opcional, en g). */
function prepVals(food, m, grams, oilOver) {
  const k = (food.k * grams) / 100, p = (food.p * grams) / 100, c = (food.c * grams) / 100, f = (food.f * grams) / 100;
  const oil = oilOver != null && oilOver >= 0 ? oilOver : (m.o * grams) / 100, x = m.x || [0, 0, 0, 0], q = grams / 100;
  return { k: Math.round(k + oil * OIL_K + x[0] * q), p: Math.round((p + x[1] * q) * 10) / 10, c: Math.round((c + x[2] * q) * 10) / 10, f: Math.round((f + oil + x[3] * q) * 10) / 10 };
}
const prepKcal100 = (m) => Math.round(m.o * OIL_K + (m.x ? m.x[0] : 0));

